// Generate realistic SVG notebook lined paper with handwritten style Arabic text
function createSampleSvg(title: string, lines: string[]): string {
  const lineSvg = lines
    .map(
      (line, i) =>
        `<line x1="40" y1="${120 + i * 40}" x2="760" y2="${120 + i * 40}" stroke="#cbd5e1" stroke-width="1.5" stroke-dasharray="2,2"/>
         <text x="740" y="${110 + i * 40}" font-family="'Amiri', serif" font-size="20" fill="#1e293b" text-anchor="end" font-weight="500">${line}</text>`
    )
    .join('\n');

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 620" width="800" height="620">
    <rect width="800" height="620" fill="#fdfbf7"/>
    <!-- Notebook margin lines -->
    <line x1="770" y1="0" x2="770" y2="620" stroke="#fca5a5" stroke-width="2"/>
    <line x1="50" y1="0" x2="50" y2="620" stroke="#93c5fd" stroke-width="1"/>
    
    <!-- Title -->
    <rect x="220" y="25" width="360" height="45" rx="6" fill="#fef3c7" stroke="#f59e0b" stroke-width="1.5"/>
    <text x="400" y="55" font-family="'Cairo', sans-serif" font-size="20" font-weight="bold" fill="#78350f" text-anchor="middle">موضوع التعبير: ${title}</text>
    
    <!-- Lines of essay -->
    ${lineSvg}

    <!-- Student stamp/signature footer -->
    <rect x="520" y="540" width="220" height="50" rx="8" fill="#f1f5f9" stroke="#94a3b8"/>
    <text x="720" y="570" font-family="'Cairo', sans-serif" font-size="14" fill="#475569" text-anchor="end">اسم الطالب: مروان أحمد (الصف التاسع)</text>
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

